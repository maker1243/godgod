// CJK(한중일) 문자 감지 - 픽셀 폰트에 없는 문자는 브라우저 기본 폰트로 폴백
const CJK_RE = /[\u3131-\uD79D\u3040-\u9FFF\u4E00-\u9FFF]/;
function hasCJK(s) { return CJK_RE.test(String(s)); }

function drawText(str, x, y, color = '#e8d9b0', scale = 1) {
  str = String(str);
  if (hasCJK(str)) {
    // 한국어/일본어/중국어: 시스템 폰트로 폴백
    ctx.fillStyle = color;
    ctx.font = 'bold ' + (7 * scale * PX) + 'px "Malgun Gothic", "Apple SD Gothic Neo", "Noto Sans KR", "Yu Gothic", "MS Gothic", sans-serif';
    ctx.textBaseline = 'top';
    // 픽셀 폰트와 유사한 위치 (약간 위로 보정)
    ctx.fillText(str, x * PX, y * PX);
    return;
  }
  str = str.toUpperCase();
  let cx = x;
  for (const ch of str) {
    const g = FONT[ch] || FONT['?'];
    for (let ry = 0; ry < 7; ry++) {
      const row = g[ry];
      for (let rx = 0; rx < 5; rx++) {
        if (row[rx] === '1') {
          ctx.fillStyle = color;
          ctx.fillRect((cx + rx * scale) * PX, (y + ry * scale) * PX, PX * scale, PX * scale);
        }
      }
    }
    cx += 6 * scale;
  }
}
function textWidth(str, scale = 1) {
  str = String(str);
  if (hasCJK(str)) {
    // Canvas measureText로 실제 픽셀 폭 측정 후 논리 좌표로 환산
    try {
      const saved = ctx.font;
      ctx.font = 'bold ' + (7 * scale * PX) + 'px "Malgun Gothic", "Apple SD Gothic Neo", "Noto Sans KR", "Yu Gothic", "MS Gothic", sans-serif';
      const w = ctx.measureText(str).width / PX;
      ctx.font = saved;
      return w;
    } catch(e) {
      // ctx가 없을 때 (초기화 이전) 대략치
      let total = 0;
      for (const c of str) total += CJK_RE.test(c) ? 8 : 6;
      return total * scale;
    }
  }
  return str.length * 6 * scale;
}
